#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Fit annual GPP–RWI mixed models for tree-ring chronologies.

This code starts from an annual analysis table with the detrended and
standardized variables listed below. It does not recreate the upstream
tree-ring chronologies, extract gridded GPP, or choose accumulation windows.

Required input columns
----------------------
site, Year, Lat, Lon, grid_key, RWI_detrended_z, plus the two product-specific
GPP columns:

    GLASS: GPP_current_iav_z, GPP_previous_iav_z
    BESS:  BESS_GPP_current_iav_z, BESS_GPP_previous_iav_z

The previous-year column must represent GPP in the actual calendar year t-1;
it must not be generated by shifting to the last observed row after gaps.

Model
-----
The model includes current-year and previous-year GPP, categorical year fixed
effects, a GPP-grid random intercept, and a chronology-specific random intercept
and two random slopes with an unstructured covariance matrix. It is fitted by
maximum likelihood using R and the lme4 package, invoked from this Python script.
A singular fit is reported so the covariance estimates can be checked.

Example
-------
python quantify_gpp_rwi_relationship.py --input annual_analysis_table.csv \
    --product GLASS --output-dir outputs/glass


Dependencies: numpy, pandas, Rscript, and the R package lme4.
Point --rscript to Rscript if needed.
Intervals and P values use a two-sided asymptotic Wald normal reference.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import warnings
from pathlib import Path

import numpy as np
import pandas as pd


PRODUCT_COLUMNS = {
    "GLASS": ("GPP_current_iav_z", "GPP_previous_iav_z"),
    "BESS": ("BESS_GPP_current_iav_z", "BESS_GPP_previous_iav_z"),
}
CURRENT = "GPP_current_M0_z"
PREVIOUS = "GPP_previous_M0_z"
RESPONSE = "RWI_detrended_z"
MIN_YEARS = 10


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True,
                        help="CSV containing the annual, preprocessed chronology–year table")
    parser.add_argument("--product", choices=sorted(PRODUCT_COLUMNS), required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--maxiter", type=int, default=500,
                        help="Optimizer evaluation control; minimum 10,000 evaluations")
    parser.add_argument("--rscript", default="Rscript",
                        help="Rscript executable for the intercepts model")
    parser.add_argument("--prepare-only", action="store_true",
                        help="Audit sample selection and write membership, without fitting")
    return parser.parse_args()


def prepare_sample(path: Path, product: str) -> tuple[pd.DataFrame, dict]:
    current_source, previous_source = PRODUCT_COLUMNS[product]
    required = ["site", "Year", "Lat", "Lon", "grid_key", RESPONSE,
                current_source, previous_source]
    if not path.is_file():
        raise FileNotFoundError(path)
    header = pd.read_csv(path, nrows=0).columns
    missing = sorted(set(required).difference(header))
    if missing:
        raise ValueError("Missing required input columns: " + ", ".join(missing))

    df = pd.read_csv(path, usecols=required, dtype={"site": "string", "grid_key": "string"})
    n_input = len(df)
    if df.duplicated(["site", "Year"]).any():
        raise ValueError("Input contains duplicate chronology–year rows (site, Year).")
    if df["site"].isna().any() or df["site"].str.strip().eq("").any():
        raise ValueError("Chronology identifiers must be nonempty.")
    if df["grid_key"].isna().any() or df["grid_key"].str.strip().eq("").any():
        raise ValueError("GPP-grid identifiers must be nonempty.")

    numerical = ["Year", "Lat", "Lon", RESPONSE, current_source, previous_source]
    for name in numerical:
        df[name] = pd.to_numeric(df[name], errors="coerce")
    finite = np.isfinite(df[numerical].to_numpy(dtype=float)).all(axis=1)
    df = df.loc[finite].copy()
    n_complete = len(df)
    if not np.equal(df["Year"], np.floor(df["Year"])).all():
        raise ValueError("Year must contain integer calendar years.")
    df["Year"] = df["Year"].astype(int)
    df = df.rename(columns={current_source: CURRENT, previous_source: PREVIOUS})

    # Apply the minimum after every model-specific complete-case exclusion.
    counts = df.groupby("site", observed=True).size()
    keep_ids = counts.index[counts >= MIN_YEARS]
    df = df.loc[df["site"].isin(keep_ids)].copy()
    df = df.sort_values(["site", "Year"]).reset_index(drop=True)
    if df.empty:
        raise ValueError("No chronology has at least 10 complete model years.")
    if (df.groupby("site", observed=True)["grid_key"].nunique() > 1).any():
        raise ValueError("Each chronology must map to a single GPP grid cell.")
    year_levels = sorted(df["Year"].unique().tolist())
    df["Year"] = pd.Categorical(df["Year"], categories=year_levels, ordered=True)

    audit = {
        "product": product,
        "input_rows": n_input,
        "complete_case_rows": n_complete,
        "rows_after_minimum_10_years": len(df),
        "excluded_incomplete_rows": n_input - n_complete,
        "excluded_short_chronology_rows": n_complete - len(df),
        "chronologies": int(df["site"].nunique()),
        "gpp_grid_cells": int(df["grid_key"].nunique()),
        "first_model_year": int(year_levels[0]),
        "last_model_year": int(year_levels[-1]),
        "minimum_complete_years_per_chronology": MIN_YEARS,
        "current_column_in_source": current_source,
        "previous_column_in_source": previous_source,
    }
    return df, audit


def save_sample(df: pd.DataFrame, audit: dict, output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    df[["site", "Year", "grid_key", "Lat", "Lon"]].to_csv(
        output_dir / "M0_sample_membership.csv", index=False)
    with (output_dir / "M0_sample_audit.json").open("w", encoding="utf-8") as file:
        json.dump(audit, file, indent=2, ensure_ascii=False)


R_INTERCEPT_MODEL = r'''
args <- commandArgs(trailingOnly = TRUE)
input_file <- args[1]
output_dir <- args[2]
max_iter <- as.integer(args[3])
if (!requireNamespace("lme4", quietly = TRUE)) {
    stop("The R package lme4 is required for the intercepts model.")
}
d <- read.csv(input_file, stringsAsFactors = FALSE, check.names = FALSE,
              colClasses = c(site = "character", grid_key = "character"))
d$site <- factor(d$site)
d$grid_key <- factor(d$grid_key)
d$Year <- factor(d$Year)
contrasts(d$Year) <- contr.sum(nlevels(d$Year))
fit <- lme4::lmer(
    RWI_detrended_z ~ GPP_current_M0_z + GPP_previous_M0_z + Year +
        (1 + GPP_current_M0_z + GPP_previous_M0_z | site) + (1 | grid_key),
    data = d, REML = FALSE,
    control = lme4::lmerControl(optimizer = "bobyqa", optCtrl = list(maxfun = max_iter))
)
cf <- as.data.frame(coef(summary(fit)))
cf$term <- rownames(cf)
names(cf)[1:2] <- c("estimate", "standard_error")
cf$z_statistic <- cf$estimate / cf$standard_error
cf$p_two_sided <- 2 * pnorm(-abs(cf$z_statistic))
cf$ci95_lower <- cf$estimate - qnorm(0.975) * cf$standard_error
cf$ci95_upper <- cf$estimate + qnorm(0.975) * cf$standard_error
write.csv(cf[,c("term", "estimate", "standard_error", "z_statistic", "p_two_sided", "ci95_lower", "ci95_upper")],
          file.path(output_dir, "fixed.csv"), row.names = FALSE)
vc <- lme4::VarCorr(fit)
write.csv(as.matrix(vc$site), file.path(output_dir, "site_covariance.csv"), row.names = TRUE)
site_effects <- as.data.frame(lme4::ranef(fit)$site)
site_effects$site <- rownames(site_effects)
write.csv(site_effects, file.path(output_dir, "site_effects.csv"), row.names = FALSE)
grid_effects <- as.data.frame(lme4::ranef(fit)$grid_key)
grid_effects$grid_key <- rownames(grid_effects)
write.csv(grid_effects, file.path(output_dir, "grid_effects.csv"), row.names = FALSE)
y <- d$RWI_detrended_z
total_ss <- sum((y - mean(y))^2)
warnings <- fit@optinfo$conv$lme4$messages
opt_code <- fit@optinfo$conv$opt
info <- data.frame(
    log_likelihood = as.numeric(logLik(fit)), aic = AIC(fit), bic = BIC(fit),
    residual_variance = sigma(fit)^2,
    grid_intercept_variance = as.numeric(vc$grid_key[1, 1]),
    fixed_prediction_r2_in_sample = 1 - sum((y - predict(fit, re.form = NA))^2) / total_ss,
    conditional_prediction_r2_in_sample = 1 - sum((y - fitted(fit))^2) / total_ss,
    singular = lme4::isSingular(fit),
    optimizer_code = if (length(opt_code)) paste(opt_code, collapse = "; ") else "0",
    convergence_messages = if (length(warnings)) paste(warnings, collapse = "; ") else "",
    r_version = as.character(getRversion()), lme4_version = as.character(packageVersion("lme4"))
)
write.csv(info, file.path(output_dir, "info.csv"), row.names = FALSE, na = "")
'''


def fit_intercepts(df: pd.DataFrame, audit: dict, maxiter: int,
                   rscript: str, output_dir: Path) -> None:
    executable = shutil.which(rscript) or (rscript if Path(rscript).is_file() else None)
    if not executable:
        raise RuntimeError("Rscript was not found. Install R and lme4, or specify --rscript.")
    with tempfile.TemporaryDirectory(prefix="gpp_rwi_m0_") as directory:
        tmp = Path(directory)
        source = tmp / "fit_model.R"
        source.write_text(R_INTERCEPT_MODEL, encoding="utf-8")
        df.to_csv(tmp / "input.csv", index=False)
        try:
            run = subprocess.run(
                [str(executable), "--vanilla", str(source), str(tmp / "input.csv"),
                 str(tmp), str(max(10000, maxiter * 20))], capture_output=True, text=True,
                encoding="utf-8", errors="replace", check=False,
            )
        except OSError as error:
            raise RuntimeError(f"Could not run Rscript: {error}") from error
        if run.returncode:
            raise RuntimeError("R/lme4 model fitting failed: " + (run.stderr or run.stdout))
        fixed_effects = pd.read_csv(tmp / "fixed.csv")
        fixed_effects.to_csv(output_dir / "M0_fixed_effects_all.csv", index=False)
        fixed_effects.loc[fixed_effects["term"].isin([CURRENT, PREVIOUS])].to_csv(
            output_dir / "M0_key_fixed_effects.csv", index=False)
        covariance = pd.read_csv(tmp / "site_covariance.csv", index_col=0)
        covariance.stack().rename("covariance").reset_index().rename(
            columns={"level_0": "row_term", "level_1": "column_term"}
        ).to_csv(output_dir / "M0_chronology_random_effects_covariance.csv", index=False)
        pd.read_csv(tmp / "site_effects.csv", dtype={"site": "string"}).to_csv(
            output_dir / "M0_chronology_random_effects.csv", index=False)
        pd.read_csv(tmp / "grid_effects.csv", dtype={"grid_key": "string"}).to_csv(
            output_dir / "M0_grid_random_intercepts.csv", index=False)
        info = pd.read_csv(tmp / "info.csv", keep_default_na=False).iloc[0].to_dict()
        information = {
            **audit, **info,
            "model": "intercepts",
            "formula": "RWI_detrended_z ~ current + previous + Year + (1 + current + previous | site) + (1 | grid_key)",
            "estimator": "maximum likelihood", "year_coding": "sum-to-zero",
            "chronology_random_intercept": True, "gpp_grid_random_intercept": True,
            "inference": "two-sided asymptotic normal Wald intervals and P values",
            "r_stdout": run.stdout, "r_stderr": run.stderr,
            "python_version": sys.version.split()[0],
        }
        with (output_dir / "M0_model_information.json").open("w", encoding="utf-8") as file:
            json.dump(information, file, indent=2, ensure_ascii=False)
        if str(info.get("singular")).lower() == "true":
            warnings.warn("The intercepts model is singular; inspect its variance and covariance estimates.")
        if str(info.get("optimizer_code")) not in ("0", "0.0", ""):
            warnings.warn("The intercepts model optimizer did not report successful convergence.")
        print(fixed_effects.loc[fixed_effects["term"].isin([CURRENT, PREVIOUS])].to_string(index=False))


def main() -> None:
    args = parse_args()
    if args.maxiter < 1:
        raise ValueError("--maxiter must be positive")
    df, audit = prepare_sample(args.input, args.product)
    save_sample(df, audit, args.output_dir)
    print(json.dumps(audit, indent=2, ensure_ascii=False))
    if args.prepare_only:
        return
    print("Fitting the GPP–RWI model with grid and chronology random intercepts.")
    fit_intercepts(df, audit, args.maxiter, args.rscript, args.output_dir)
    print("Saved fitted model results to", args.output_dir)


if __name__ == "__main__":
    main()
